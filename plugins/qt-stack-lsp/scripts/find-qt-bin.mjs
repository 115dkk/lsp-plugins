import {
  existsSync,
  lstatSync,
  readFileSync,
  readdirSync,
  statSync,
} from "node:fs";
import os from "node:os";
import path from "node:path";

const SKIPPED_DIRECTORIES = new Set([".git", "node_modules", ".cache"]);
const QMAKE_MAKEFILES = new Set(["Makefile", "Makefile.Release", "Makefile.Debug"]);

function safeIsFile(filePath) {
  try {
    return statSync(filePath).isFile();
  } catch {
    return false;
  }
}

function safeDirectoryEntries(directory) {
  try {
    return readdirSync(directory, { withFileTypes: true });
  } catch {
    return [];
  }
}

function stripQuotes(value) {
  const trimmed = value.trim();
  if (trimmed.length >= 2 && trimmed.startsWith('"') && trimmed.endsWith('"')) {
    return trimmed.slice(1, -1);
  }
  return trimmed;
}

function findProjectRoot(startDirectory) {
  let directory = path.resolve(startDirectory);

  while (true) {
    try {
      if (existsSync(path.join(directory, ".git"))) {
        return directory;
      }
    } catch {
      // Keep walking when a parent cannot be inspected.
    }

    const parent = path.dirname(directory);
    if (parent === directory) {
      return path.resolve(startDirectory);
    }
    directory = parent;
  }
}

function walkFiles(root, maximumDepth) {
  const files = [];

  function visit(directory, depth) {
    for (const entry of safeDirectoryEntries(directory)) {
      const entryPath = path.join(directory, entry.name);
      let stats;
      try {
        stats = lstatSync(entryPath);
      } catch {
        continue;
      }

      if (stats.isSymbolicLink()) {
        continue;
      }
      if (stats.isFile()) {
        files.push({ filePath: entryPath, mtimeMs: stats.mtimeMs });
        continue;
      }
      if (
        stats.isDirectory() &&
        depth < maximumDepth &&
        !SKIPPED_DIRECTORIES.has(entry.name.toLowerCase())
      ) {
        visit(entryPath, depth + 1);
      }
    }
  }

  visit(root, 0);
  return files;
}

function projectCandidates(startDirectory) {
  const root = findProjectRoot(startDirectory);
  const candidates = [];

  for (const source of walkFiles(root, 2)) {
    const name = path.basename(source.filePath);
    let contents;

    if (QMAKE_MAKEFILES.has(name)) {
      try {
        contents = readFileSync(source.filePath, "utf8");
      } catch {
        continue;
      }
      if (!contents.split(/\r?\n/, 15).some((line) => line.includes("Generated by qmake"))) {
        continue;
      }
      const match = contents.match(/^QMAKE\s*=\s*(.+)$/m);
      if (match) {
        const qmakePath = stripQuotes(match[1]);
        const absoluteQmake = path.isAbsolute(qmakePath)
          ? path.normalize(qmakePath)
          : path.resolve(path.dirname(source.filePath), qmakePath);
        candidates.push({
          directory: path.dirname(absoluteQmake),
          mtimeMs: source.mtimeMs,
          sourcePath: source.filePath,
          sourceRank: 0,
        });
      }
      continue;
    }

    if (name !== "CMakeCache.txt") {
      continue;
    }
    try {
      contents = readFileSync(source.filePath, "utf8");
    } catch {
      continue;
    }

    const qtDirectory = contents.match(/^Qt6_DIR:[A-Z]+=(.+)$/m);
    if (qtDirectory) {
      candidates.push({
        directory: path.resolve(stripQuotes(qtDirectory[1]), "..", "..", "..", "bin"),
        mtimeMs: source.mtimeMs,
        sourcePath: source.filePath,
        sourceRank: 0,
      });
    }

    const qmakeExecutable = contents.match(/^QT_QMAKE_EXECUTABLE:FILEPATH=(.+)$/m);
    if (qmakeExecutable) {
      const qmakePath = stripQuotes(qmakeExecutable[1]);
      const absoluteQmake = path.isAbsolute(qmakePath)
        ? path.normalize(qmakePath)
        : path.resolve(path.dirname(source.filePath), qmakePath);
      candidates.push({
        directory: path.dirname(absoluteQmake),
        mtimeMs: source.mtimeMs,
        sourcePath: source.filePath,
        sourceRank: 1,
      });
    }
  }

  candidates.sort(
    (left, right) =>
      right.mtimeMs - left.mtimeMs ||
      left.sourcePath.localeCompare(right.sourcePath) ||
      left.sourceRank - right.sourceRank,
  );
  return candidates.map((candidate) => candidate.directory);
}

function compareVersionsDescending(left, right) {
  const leftParts = left.split(/[^0-9]+/).filter(Boolean).map(Number);
  const rightParts = right.split(/[^0-9]+/).filter(Boolean).map(Number);
  const length = Math.max(leftParts.length, rightParts.length);

  for (let index = 0; index < length; index += 1) {
    const difference = (rightParts[index] ?? 0) - (leftParts[index] ?? 0);
    if (difference !== 0) {
      return difference;
    }
  }
  return left.localeCompare(right);
}

function versionDirectories(root) {
  return safeDirectoryEntries(root)
    .filter((entry) => entry.isDirectory() && /^\d+(?:\.\d+)+/.test(entry.name))
    .map((entry) => entry.name)
    .sort(compareVersionsDescending);
}

function windowsStandardDirectories(env) {
  const roots = ["C:\\Qt"];
  if (env.USERPROFILE) {
    roots.push(path.join(env.USERPROFILE, "Qt"));
  }

  const installations = [];
  roots.forEach((root, rootRank) => {
    for (const version of versionDirectories(root)) {
      for (const arch of safeDirectoryEntries(path.join(root, version))) {
        if (!arch.isDirectory()) {
          continue;
        }
        installations.push({
          archRank: /^msvc.*_64$/i.test(arch.name) ? 0 : 1,
          directory: path.join(root, version, arch.name, "bin"),
          rootRank,
          version,
        });
      }
    }
  });

  installations.sort(
    (left, right) =>
      compareVersionsDescending(left.version, right.version) ||
      left.rootRank - right.rootRank ||
      left.archRank - right.archRank ||
      left.directory.localeCompare(right.directory),
  );
  return installations.map((installation) => installation.directory);
}

function unixQtDirectories(root, architecture) {
  const directories = [];
  for (const version of versionDirectories(root)) {
    directories.push(path.join(root, version, architecture, "bin"));
  }
  return directories;
}

function standardDirectories(env) {
  if (process.platform === "win32") {
    return windowsStandardDirectories(env);
  }

  const home = env.HOME || os.homedir();
  if (process.platform === "darwin") {
    return [
      ...unixQtDirectories(path.join(home, "Qt"), "macos"),
      "/opt/homebrew/opt/qt/bin",
      "/usr/local/opt/qt/bin",
    ];
  }

  return [
    ...unixQtDirectories(path.join(home, "Qt"), "gcc_64"),
    "/usr/lib/qt6/bin",
    "/usr/lib64/qt6/bin",
    "/usr/lib/x86_64-linux-gnu/qt6/bin",
    "/usr/lib/aarch64-linux-gnu/qt6/bin",
  ];
}

function pathDirectories(env) {
  const value = env.PATH ?? env.Path ?? env.path ?? "";
  return value.split(path.delimiter).filter(Boolean).map((directory) => path.resolve(directory));
}

function deduplicateDirectories(directories) {
  const seen = new Set();
  const result = [];

  for (const directory of directories) {
    if (typeof directory !== "string" || directory.trim() === "") {
      continue;
    }
    const absolute = path.resolve(directory);
    const key = process.platform === "win32" ? absolute.toLowerCase() : absolute;
    if (!seen.has(key)) {
      seen.add(key);
      result.push(absolute);
    }
  }
  return result;
}

export function candidateBinDirs({ startDir = process.cwd(), env = process.env } = {}) {
  try {
    const directories = [];
    if (env.QT_STACK_QT_BIN) {
      directories.push(env.QT_STACK_QT_BIN);
    }
    for (const variable of ["QTDIR", "QT_ROOT_DIR"]) {
      if (env[variable]) {
        directories.push(path.join(env[variable], "bin"));
      }
    }
    directories.push(...projectCandidates(startDir));
    directories.push(...pathDirectories(env));
    directories.push(...standardDirectories(env));
    return deduplicateDirectories(directories);
  } catch {
    return [];
  }
}

export function findQtTool(toolName, { startDir = process.cwd(), env = process.env } = {}) {
  try {
    const executableName = process.platform === "win32" ? `${toolName}.exe` : toolName;
    for (const directory of candidateBinDirs({ startDir, env })) {
      const candidate = path.join(directory, executableName);
      if (safeIsFile(candidate)) {
        return path.resolve(candidate);
      }
    }

    if (toolName === "qmlls") {
      const fallbackName = process.platform === "win32" ? "pyside6-qmlls.exe" : "pyside6-qmlls";
      for (const directory of pathDirectories(env)) {
        const candidate = path.join(directory, fallbackName);
        if (safeIsFile(candidate)) {
          return path.resolve(candidate);
        }
      }
    }
  } catch {
    // Discovery is best effort. Callers decide how to handle a missing tool.
  }
  return null;
}
