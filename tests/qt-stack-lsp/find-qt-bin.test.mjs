import assert from "node:assert/strict";
import {
  mkdirSync,
  mkdtempSync,
  rmSync,
  utimesSync,
  writeFileSync,
} from "node:fs";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import {
  candidateBinDirs,
  findQtTool,
} from "../../plugins/qt-stack-lsp/scripts/find-qt-bin.mjs";

const executableSuffix = process.platform === "win32" ? ".exe" : "";

function workspace(t) {
  const directory = mkdtempSync(path.join(os.tmpdir(), "qt-stack-find-"));
  t.after(() => rmSync(directory, { force: true, recursive: true }));
  return directory;
}

function environment(home, extra = {}) {
  return {
    HOME: home,
    PATH: "",
    USERPROFILE: home,
    ...extra,
  };
}

function fakeTool(directory, name) {
  mkdirSync(directory, { recursive: true });
  const filePath = path.join(directory, `${name}${executableSuffix}`);
  writeFileSync(filePath, "");
  return filePath;
}

function qmakeFile(filePath, qmakePath) {
  mkdirSync(path.dirname(filePath), { recursive: true });
  writeFileSync(
    filePath,
    [
      "#############################################################################",
      "# Generated by qmake (3.1) (Qt 6.12.0)",
      "# Project:  ../App/App.pro",
      `QMAKE         = \"${qmakePath}\"`,
      "",
    ].join("\n"),
  );
}

test("QT_STACK_QT_BIN wins over every later candidate", (t) => {
  const root = workspace(t);
  const overrideBin = path.join(root, "override", "bin");
  const qtdirBin = path.join(root, "qtdir", "bin");
  const expected = fakeTool(overrideBin, "qmlls");
  fakeTool(qtdirBin, "qmlls");

  const found = findQtTool("qmlls", {
    startDir: root,
    env: environment(root, {
      QTDIR: path.dirname(qtdirBin),
      QT_STACK_QT_BIN: overrideBin,
    }),
  });

  assert.equal(found, path.resolve(expected));
});

test("QTDIR contributes its bin directory", (t) => {
  const root = workspace(t);
  const qtRoot = path.join(root, "Qt", "6.12.0", "msvc2022_64");
  const expected = fakeTool(path.join(qtRoot, "bin"), "uic");

  assert.equal(
    findQtTool("uic", {
      startDir: root,
      env: environment(root, { QTDIR: qtRoot }),
    }),
    path.resolve(expected),
  );
});

test("a qmake Makefile is discovered from a nested project directory", (t) => {
  const root = workspace(t);
  mkdirSync(path.join(root, ".git"));
  const nested = path.join(root, "src", "widgets");
  mkdirSync(nested, { recursive: true });
  const qtBin = path.join(root, "Qt", "6.12.0", "msvc2022_64", "bin");
  const expected = fakeTool(qtBin, "rcc");
  qmakeFile(path.join(root, "build", "Makefile.Release"), path.join(qtBin, `qmake${executableSuffix}`));

  assert.equal(
    findQtTool("rcc", { startDir: nested, env: environment(root) }),
    path.resolve(expected),
  );
});

test("a candidate without the requested tool is skipped", (t) => {
  const root = workspace(t);
  const emptyBin = path.join(root, "empty-bin");
  mkdirSync(emptyBin);
  const qtRoot = path.join(root, "working-qt");
  const expected = fakeTool(path.join(qtRoot, "bin"), "uic");

  assert.equal(
    findQtTool("uic", {
      startDir: root,
      env: environment(root, {
        QTDIR: qtRoot,
        QT_STACK_QT_BIN: emptyBin,
      }),
    }),
    path.resolve(expected),
  );
});

test("CMakeCache Qt6_DIR resolves to the Qt bin directory", (t) => {
  const root = workspace(t);
  mkdirSync(path.join(root, ".git"));
  const qtRoot = path.join(root, "Qt", "6.12.0", "gcc_64");
  const qt6Directory = path.join(qtRoot, "lib", "cmake", "Qt6");
  const expected = fakeTool(path.join(qtRoot, "bin"), "qmlls");
  const cache = path.join(root, "build", "CMakeCache.txt");
  mkdirSync(path.dirname(cache), { recursive: true });
  writeFileSync(cache, `Qt6_DIR:PATH=${qt6Directory}\n`);

  assert.equal(
    findQtTool("qmlls", { startDir: root, env: environment(root) }),
    path.resolve(expected),
  );
});

test("newer project Makefiles contribute candidates first", (t) => {
  const root = workspace(t);
  mkdirSync(path.join(root, ".git"));
  const olderBin = path.join(root, "older-qt", "bin");
  const newerBin = path.join(root, "newer-qt", "bin");
  fakeTool(olderBin, "qmlls");
  const expected = fakeTool(newerBin, "qmlls");
  const olderMakefile = path.join(root, "build-old", "Makefile.Release");
  const newerMakefile = path.join(root, "build-new", "Makefile.Release");
  qmakeFile(olderMakefile, path.join(olderBin, `qmake${executableSuffix}`));
  qmakeFile(newerMakefile, path.join(newerBin, `qmake${executableSuffix}`));
  const now = Date.now() / 1000;
  utimesSync(olderMakefile, now - 100, now - 100);
  utimesSync(newerMakefile, now, now);

  const env = environment(root);
  const candidates = candidateBinDirs({ startDir: root, env });
  assert.ok(candidates.indexOf(path.resolve(newerBin)) < candidates.indexOf(path.resolve(olderBin)));
  assert.equal(findQtTool("qmlls", { startDir: root, env }), path.resolve(expected));
});

test("findQtTool returns null when no candidate has the tool", (t) => {
  const root = workspace(t);
  assert.equal(
    findQtTool(`missing-tool-${process.pid}-${Date.now()}`, {
      startDir: root,
      env: environment(root),
    }),
    null,
  );
});

test("qmlls falls back to pyside6-qmlls on PATH", (t) => {
  const root = workspace(t);
  const pathBin = path.join(root, "path-bin");
  const fallbackName = process.platform === "win32" ? "pyside6-qmlls.exe" : "pyside6-qmlls";
  mkdirSync(pathBin);
  const expected = path.join(pathBin, fallbackName);
  writeFileSync(expected, "");

  assert.equal(
    findQtTool("qmlls", {
      startDir: root,
      env: environment(root, { PATH: pathBin }),
    }),
    path.resolve(expected),
  );
});
